def contrast(left, right):
    assert len(left) == len(right) and left
    delta = [a - b for a, b in zip(left, right)]
    return {"mean_delta": mean(delta),
            "relative_mean_delta": mean(delta) / mean(right),
            "wins": sum(d > 0 for d in delta),
            "losses": sum(d < 0 for d in delta),
            "ties": sum(d == 0 for d in delta)}


def check(saved, computed):
    for key, value in computed.items():
        assert isclose(saved[key], value, rel_tol=1e-9, abs_tol=1e-7), key


def mean_sem(values, digits=2):
    sem = stdev(values) / sqrt(len(values))
    return f"${mean(values):.{digits}f}{{\\pm}}{sem:.{digits}f}$"


def percent(result):
    return f"{100 * result['relative_mean_delta']:+.2f}\\%"


def counts(result):
    return "/".join(str(result[k]) for k in ("wins", "losses", "ties"))


def format_hv_scale(env, value):
    if env == "mo-halfcheetah-v5":
        return f"{value / 1e6:.2f}M"
    return f"{value / 1e9:.2f}B"


def table(caption, label, columns, header, rows, size=r"\small\setlength{\tabcolsep}{4.5pt}"):
    return "\n".join([
        "% Generated by make_evidence_tables.py from completed readouts.",
        r"\begin{table}[!htbp]", r"\centering" + size,
        r"\caption{" + caption + "}", r"\label{" + label + "}",
        r"\begin{tabular}{" + columns + "}", r"\toprule",
        " & ".join(header) + r" \\", r"\midrule",
        *(" & ".join(row) + r" \\" for row in rows),
        r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
    ])


def utility_confirmation_tables(report):
    seeds = list(range(1601, 1621))
    assert report["protocol"] == "v25_capql_utility_confirmation_v1" and report["complete"]
    assert report["seeds"] == seeds
    indices = np.random.default_rng(0).integers(0, 20, (20000, 20))
    utility_rows, secondary_rows = [], []
    for env, label in ENVS[:2]:
        group = report["environments"][env]
        assert group["seeds"] == seeds
        assert [r["seed"] for r in group["runs"]] == seeds
        for run in group["runs"]:
            for method in ("v25", "capql"):
                row = run[method]
                assert (row["env"], row["method"], row["seed"], row["complete"]) == (
                    env, method, run["seed"], True)
                assert row["completed_budget"]["training_interactions"] == 75000
            assert run["v25"]["evaluation"] == run["capql"]["evaluation"]
            assert run["v25"]["mode_history"] == run["capql"]["mode_history"]
        metrics = {method: [r[method]["metrics"] for r in group["runs"]]
                   for method in ("v25", "capql")}
        utility = {method: [r["direct_utility"]["mean"] for r in rows]
                   for method, rows in metrics.items()}
        effect = contrast(utility["v25"], utility["capql"])
        saved = group["paired"]["direct_utility"]
        check(saved, effect)
        delta = np.asarray(utility["v25"]) - utility["capql"]
        np.testing.assert_allclose(saved["paired_deltas"], delta, rtol=1e-9, atol=1e-7)
        boot = delta[indices].mean(axis=1)
        ci975 = np.quantile(boot, [.0125, .9875])
        ci95 = np.quantile(boot, [.025, .975])
        np.testing.assert_allclose(saved["paired_mean_ci97_5"], ci975, rtol=1e-9, atol=1e-7)
        np.testing.assert_allclose(saved["paired_mean_ci95"], ci95, rtol=1e-9, atol=1e-7)
        utility_rows.append([
            label,
            mean_sem(utility["v25"]),
            mean_sem(utility["capql"]),
            f"{effect['mean_delta']:+.2f}",
            percent(effect),
            f"$[{ci975[0]:.2f},\\ {ci975[1]:.2f}]$",
            counts(effect),
        ])
        hv = contrast([r["final_hv"] for r in metrics["v25"]],
                      [r["final_hv"] for r in metrics["capql"]])
        check(group["paired"]["final_hv"], hv)
        times = [f"{mean(r[key] for r in metrics['v25']):.1f} / "
                 f"{mean(r[key] for r in metrics['capql']):.1f}"
                 for key in ("training_seconds", "evaluation_seconds")]
        secondary_rows.append([label, percent(hv), counts(hv), *times])
    return {
        "table_utility_confirmation.tex": table(
            "Preference-aligned direct utility $U$ at 75k training interactions across 20 "
            "paired seeds per benchmark (mean $\\pm$ SEM). Native CAPQL uses its default "
            "$22.5^\\circ$ central preference cone. Prespecified 97.5\\% marginal intervals "
            "use 20,000 paired bootstrap resamples for the two-task comparison. "
            "W/L/T reports paired seed wins/losses/ties.",
            "tab:utility_confirmation", "@{}lrrrrrr@{}",
            ["Environment", "$U$: BAMOR", "$U$: Native CAPQL", "$\\Delta U$", "Relative", "97.5\\% CI", "W/L/T"],
            utility_rows),
        "table_utility_secondary.tex": table(
            "Single-actor Pareto return-set coverage (Final HV) and wall-clock runtime on the "
            "20-seed 75k benchmark of Table~\\ref{tab:utility_confirmation}. HV reports the "
            "relative difference of cohort means (BAMOR vs.\\ native CAPQL); times are mean "
            "seconds per run on two CPU threads.",
            "tab:utility_secondary", "@{}lrrrr@{}",
            ["Environment", "Final HV", "W/L/T", "Training (s)", "Evaluation (s)"],
            secondary_rows),
    }


def full_simplex_table(report, confirmation=None):
    seeds = list(range(1601, 1621))
    assert report["protocol"] == "capql_full_simplex_completion_v1" and report["complete"]
    assert report["seeds"] == seeds
    indices = np.random.default_rng(0).integers(0, 20, (20000, 20))
    blocks = {
        "v25_minus_full_simplex": ("v25", "capql_full_simplex", []),
        "full_simplex_minus_native": ("capql_full_simplex", "capql", []),
    }
    for env, label in ENVS[:2]:
        group = report["environments"][env]
        rows = group["seed_metrics"]
        assert [r["seed"] for r in rows] == seeds
        for idx, row in enumerate(rows):
            for method in ("v25", "capql", "capql_full_simplex"):
                entry = row["methods"][method]
                assert entry["completed_budget"]["training_interactions"] == 75000
            if confirmation is not None:
                ref = confirmation["environments"][env]["runs"][idx]
                assert ref["seed"] == row["seed"]
                for method in ("v25", "capql"):
                    assert isclose(
                        row["methods"][method]["metrics"]["direct_utility"]["mean"],
                        ref[method]["metrics"]["direct_utility"]["mean"],
                        rel_tol=1e-12, abs_tol=1e-9)
                    np.testing.assert_allclose(
                        row["methods"][method]["metrics"]["direct_utility"]["per_mode"],
                        ref[method]["metrics"]["direct_utility"]["per_mode"],
                        rtol=1e-12, atol=1e-9)
                    assert isclose(
                        row["methods"][method]["metrics"]["final_hv"],
                        ref[method]["metrics"]["final_hv"],
                        rel_tol=1e-12, abs_tol=1e-9)
            for entry in row["methods"].values():
                utility = entry["metrics"]["direct_utility"]
                assert isclose(mean(utility["per_mode"]), utility["mean"], rel_tol=1e-10, abs_tol=1e-8)
        per_mode_v25 = np.asarray([r["methods"]["v25"]["metrics"]["direct_utility"]["per_mode"]
                                   for r in rows])
        per_mode_fs = np.asarray([r["methods"]["capql_full_simplex"]["metrics"]["direct_utility"]["per_mode"]
                                  for r in rows])
        np.testing.assert_allclose(
            group["per_mode_utility_mean_delta"],
            (per_mode_v25 - per_mode_fs).mean(axis=0),
            rtol=1e-9, atol=1e-7)
        for pair_key, (left_m, right_m, out_rows) in blocks.items():
            left_u = [r["methods"][left_m]["metrics"]["direct_utility"]["mean"] for r in rows]
            right_u = [r["methods"][right_m]["metrics"]["direct_utility"]["mean"] for r in rows]
            effect = contrast(left_u, right_u)
            saved_u = group["paired"][pair_key]["direct_utility"]
            check(saved_u, effect)
            delta = np.asarray(left_u) - np.asarray(right_u)
            np.testing.assert_allclose(saved_u["paired_deltas"], delta, rtol=1e-9, atol=1e-7)
            boot = delta[indices].mean(axis=1)
            ci975 = np.quantile(boot, [.0125, .9875])
            ci95 = np.quantile(boot, [.025, .975])
            np.testing.assert_allclose(saved_u["paired_mean_ci97_5"], ci975, rtol=1e-9, atol=1e-7)
            np.testing.assert_allclose(saved_u["paired_mean_ci95"], ci95, rtol=1e-9, atol=1e-7)
            hv = contrast(
                [r["methods"][left_m]["metrics"]["final_hv"] for r in rows],
                [r["methods"][right_m]["metrics"]["final_hv"] for r in rows])
            check(group["paired"][pair_key]["final_hv"], hv)
            ci = ci975 if pair_key == "v25_minus_full_simplex" else ci95
            out_rows.append([
                label,
                f"{mean_sem(left_u)} / {mean_sem(right_u)}",
                f"{effect['mean_delta']:+.2f}",
                percent(effect),
                f"$[{ci[0]:.2f},\\ {ci[1]:.2f}]$",
                counts(effect),
                percent(hv),
            ])
    lines = [
        "% Generated by make_evidence_tables.py from completed readouts.",
        r"\begin{table}[t]",
        r"\centering\footnotesize\setlength{\tabcolsep}{4pt}",
        r"\caption{Retrospective full-simplex CAPQL comparison on the inspected 20-seed cohort at 75k interactions. CAPQL changes its training sampler to $\mathrm{Dir}(\mathbf{1})$ with the same networks, losses and mode histories. BAMOR versus full-simplex CAPQL uses the follow-up's prespecified 97.5\% marginal intervals. The sampler-only contrast uses descriptive 95\% intervals.}",
        r"\label{tab:full_simplex_capql}",
        r"\begin{tabular}{@{}lrrrrrr@{}}",
        r"\toprule",
        r"Environment & $U$ means ($\pm$ SEM) & $\Delta U$ & Relative & Paired CI & W/L/T & Final HV \\",
        r"\midrule",
        r"\multicolumn{7}{@{}l}{\emph{BAMOR minus full-simplex CAPQL (97.5\% CI)}} \\",
        *(" & ".join(row) + r" \\" for row in blocks["v25_minus_full_simplex"][2]),
        r"\midrule",
        r"\multicolumn{7}{@{}l}{\emph{Full-simplex CAPQL minus native CAPQL (95\% CI)}} \\",
        *(" & ".join(row) + r" \\" for row in blocks["full_simplex_minus_native"][2]),
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
    ]
    return {"table_full_simplex_capql.tex": "\n".join(lines)}


def ant_search_table(actor_rep, critic_rep, adaptive_rep, aligned):
    records = aligned["development"]["runs"]
    specs = [
        (actor_rep["comparisons"]["new_minus_fixed"], "actor_off_blind", "original_blind",
         "Own-pref actor vs.\\ multi-candidate (quota)"),
        (critic_rep["comparisons"]["new_minus_actor_only"], "both_off_blind", "actor_off_blind",
         "Own-pref actor+critic vs.\\ own-pref actor (quota)"),
        (adaptive_rep["comparisons"]["new_minus_adaptive"], "actor_off_adaptive", "original_adaptive",
         "Own-pref actor vs.\\ multi-candidate (progress-routed)"),
        (critic_rep["comparisons"]["new_minus_capql"], "both_off_blind", "capql",
         "Own-pref actor+critic (quota) vs.\\ CAPQL"),
    ]
    rows = []
    for saved, left, right, label in specs:
        computed = {}
        for metric in ("mode0_mixed_energy_utility", "all_mode_direct_utility", "final_hv"):
            a = [row["conditions"][left][metric] for row in records]
            b = [row["conditions"][right][metric] for row in records]
            delta = np.subtract(a, b)
            np.testing.assert_allclose(saved[metric]["paired_deltas"], delta, rtol=1e-9, atol=1e-6)
            computed[metric] = contrast(a, b)
            # Reconstructed controls can differ by floating-point cancellation at exact ties.
            ties = np.isclose(delta, 0, atol=1e-6, rtol=0)
            computed[metric].update(
                wins=int((delta > 1e-6).sum()), losses=int((delta < -1e-6).sum()),
                ties=int(ties.sum()))
            check(saved[metric], computed[metric])
        u = computed["mode0_mixed_energy_utility"]
        hv = computed["final_hv"]
        rows.append([
            label,
            f"{u['mean_delta']:+.1f}",
            counts(u),
            f"{100 * hv['relative_mean_delta']:+.2f}\\%",
            counts(hv),
        ])
    return {
        "table_ant_search.tex": table(
            "Diagnosing cross-preference candidate search on three-objective Ant at 75k "
            "interactions (five paired seeds). $\\Delta U_0$ measures mixed-energy preference "
            "utility ($0 < w_{\\mathrm{energy}} < 1$) in mode~0; Final HV averages all modes.",
            "tab:ant_search", "@{}lrrrr@{}",
            ["Diagnostic contrast", "$\\Delta U_0$", "W/L/T", "Final HV", "W/L/T"],
            rows),
    }


def build():
    data = {key: json.loads((RESULTS / path).read_text())
            for key, path in SOURCES.items()}
    archive_rows, selector_rows, final_rows = [], [], []
    for env, label in ENVS:
        old = data["archive"]["environments"][env]
        seeds = list(range(1011, 1026 if env == "mo-halfcheetah-v5" else 1016))
        assert old["seeds"] == seeds
        assert [run["seed"] for run in old["runs"]] == seeds

        arch_hv = [r["legacy_adaptive"]["archive_hv"] for r in old["runs"]]
        fin_hv = [r["legacy_adaptive"]["final_hv"] for r in old["runs"]]
        internal_gain = contrast(arch_hv, fin_hv)
        archive_rows.append([
            label,
            str(len(seeds)),
            format_hv_scale(env, mean(arch_hv)),
            format_hv_scale(env, mean(fin_hv)),
            percent(internal_gain),
            counts(internal_gain),
        ])

        selectors = {}
        for metric in ("archive_hv", "final_hv"):
            left = [r["legacy_adaptive"][metric] for r in old["runs"]]
            selectors[metric] = contrast(
                left, [r["legacy_blind"][metric] for r in old["runs"]])
        selector_rows.append([label, str(len(seeds)), percent(selectors["archive_hv"]),
                              counts(selectors["archive_hv"]),
                              percent(selectors["final_hv"]), counts(selectors["final_hv"])])

        fresh = data["final"]["environments"][env]
        assert fresh["seeds"] == list(range(1201, 1206))
        assert [r["seed"] for r in fresh["runs"]] == fresh["seeds"]
        for run in fresh["runs"]:
            assert run["v25"]["complete"] and run["capql"]["complete"]
            assert run["v25"]["evaluation"] == run["capql"]["evaluation"]
            assert run["v25"]["mode_history"] == run["capql"]["mode_history"]
        hv = contrast([r["v25"]["metrics"]["final_hv"] for r in fresh["runs"]],
                      [r["capql"]["metrics"]["final_hv"] for r in fresh["runs"]])
        utility = {m: [r[m]["metrics"]["direct_utility"]["mean"]
                       for r in fresh["runs"]] for m in ("v25", "capql")}
        du = contrast(utility["v25"], utility["capql"])
        check(fresh["paired"]["final_hv"], hv)
        check(fresh["paired"]["direct_utility"], du)
        final_rows.append([label, percent(hv), counts(hv),
                           f"{mean(utility['v25']):.1f} / {mean(utility['capql']):.1f}",
                           f"{du['mean_delta']:+.1f}", counts(du)])

    pairwise = data["pairwise"]
    assert pairwise["seeds"] == list(range(1301, 1306))
    assert [r["seed"] for r in pairwise["runs"]] == pairwise["seeds"]
    pairs = [("pairwise_adaptive", "base_adaptive", "Residual effect, progress-routed"),
             ("pairwise_blind", "base_blind", "Residual effect, quota-regulated"),
             ("pairwise_adaptive", "pairwise_blind", "Routing effect, residual actor"),
             ("base_adaptive", "base_blind", "Routing effect, base actor"),
             ("pairwise_adaptive", "capql", "Residual progress-routed vs.\\ CAPQL")]
    ant_rows = []
    for left, right, label in pairs:
        group = pairwise["comparisons"][f"{left}_minus_{right}"]
        for metric, saved in group.items():
            check(saved, contrast([r["metrics"][left][metric] for r in pairwise["runs"]],
                                  [r["metrics"][right][metric] for r in pairwise["runs"]]))
        u = group["mode0_mixed_energy_utility"]
        hv = group["final_hv"]
        ant_rows.append([label, f"{u['mean_delta']:+.1f}", counts(u), percent(hv), counts(hv)])

    return {
        **utility_confirmation_tables(data["utility20"]),
        **full_simplex_table(data["full_simplex"], data["utility20"]),
        **ant_search_table(data["ant_actor"], data["ant_critic"], data["ant_adaptive"],
                           align_ant(RESULTS)),
        "table_matched_archive.tex": table(
            "Multi-snapshot archive coverage (19 retained actors) versus single final-actor "
            "coverage within BAMOR at 50k interactions, evaluated with the final context "
            "encoder across common locked modes and preference grids.",
            "tab:matched_archive", "@{}lrrrrr@{}",
            ["Environment", "$n$", "19-Actor Archive HV", "Final-Actor HV", "Relative Gain", "W/L/T"],
            archive_rows),
        "table_selector_effect.tex": table(
            "Marginal contribution of online progress routing over the score-neutral "
            "Quota-Regulated Portfolio at 50k interactions on the cohorts of "
            "Table~\\ref{tab:matched_archive}.",
            "tab:selector_effect", "@{}lrrrrr@{}",
            ["Environment", "$n$", "Archive HV", "W/L/T", "Final HV", "W/L/T"],
            selector_rows),
        "table_final_policy.tex": table(
            "Exploratory five-seed 75k benchmark across all three environments, separate from "
            "the 20-seed study in Tables~\\ref{tab:utility_confirmation}--"
            "\\ref{tab:full_simplex_capql}. HV is BAMOR relative to native CAPQL.",
            "tab:final_policy", "@{}lrrrrr@{}",
            ["Environment", "Final HV", "W/L/T", "$U$: BAMOR / CAPQL", "$\\Delta U$", "W/L/T"],
            final_rows),
        "table_ant_pairwise.tex": table(
            "Pairwise preference-residual actor crossed with progress-routed versus "
            "quota-regulated allocation on Ant at 75k (five paired seeds). All four BAMOR "
            "arms use own-preference actor and critic updates.",
            "tab:ant_pairwise", "@{}lrrrr@{}",
            ["Contrast", "$\\Delta U_0$", "W/L/T", "Final HV", "W/L/T"],
            ant_rows),
    }


if __name__ == "__main__":
    outputs = build()
    for name, content in outputs.items():
        (HERE / name).write_text(content)
    print(f"Wrote {len(outputs)} tables after validating the compact evidence")
